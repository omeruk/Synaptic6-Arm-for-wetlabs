"""Runs the whole analysis and writes docs/results.md plus the figures.

    python analysis/run_analysis.py
"""
import os, sys
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

sys.path.insert(0, os.path.dirname(__file__))
import kinematics as kin
import dynamics as dyn
from params import Q_MIN, Q_MAX, build_components
from actuators import ACTUATORS, ASSUMED_BACKLASH_ARCMIN
import error_budget as eb

ROOT = os.path.join(os.path.dirname(__file__), "..")
IMG = os.path.join(ROOT, "docs", "img")
os.makedirs(IMG, exist_ok=True)
SF = 1.5
LOW_BACKLASH = {2: 10, 3: 10}   # arcmin limit for the big joints (that is where it hurts)
ALPHA = 5.0
JOINTS = ["J1", "J2", "J3", "J4", "J5", "J6"]


def workspace(n=60_000, seed=0):
    rng = np.random.default_rng(seed)
    qs = rng.uniform(Q_MIN, Q_MAX, size=(n, 6))
    pts = np.array([kin.fk(q)[:3, 3] for q in qs])
    man = np.array([kin.manipulability(q) for q in qs])
    return qs, pts, man


def pick(need_rated, need_peak, max_backlash=None):
    """Lightest actuator whose rated torque covers the holding need and whose
    peak torque covers the static+dynamic need. With max_backlash set, only
    actuators with a known backlash at or below it (arcmin) are considered."""
    ok = [(v["mass"], k) for k, v in ACTUATORS.items()
          if v["rated"] >= need_rated and v["peak"] >= need_peak
          and (max_backlash is None
               or (v["backlash"] is not None and v["backlash"] <= max_backlash))]
    return min(ok)[1] if ok else "none in table"


def select_actuators(g, payload=0.5, iters=8):
    """Pick actuators for J2..J5, feed their masses back into the model and
    repeat until the choice stops changing (heavier motor -> more load)."""
    choice = {}
    for _ in range(iters):
        mass = {j: ACTUATORS[c]["mass"] for j, c in choice.items() if c in ACTUATORS}
        comps = build_components(g, payload=payload, act_mass=mass)
        st, sd, _ = dyn.worst_case(n=4000, alpha=ALPHA, comps=comps, seed=7)
        new = {j + 1: pick(st[j] * SF, sd[j] * SF, LOW_BACKLASH.get(j + 1)) for j in range(1, 6)}
        if new == choice:
            break
        choice = new
    return choice


def main():
    g = kin.GEO
    choice = select_actuators(g)
    act_mass = {j: ACTUATORS[c]["mass"] for j, c in choice.items() if c in ACTUATORS}
    comps = build_components(g, act_mass=act_mass)
    out = []
    out.append("# Results (auto-generated by analysis/run_analysis.py)\n")
    out.append("Design assumptions come from `analysis/params.py`. Actuator numbers are "
               "approximate, see `analysis/actuators.py`.\n")
    out.append(f"- Geometry: d1={g.d1*1e3:.0f} mm, a2={g.a2*1e3:.0f} mm, d4={g.d4*1e3:.0f} mm, "
               f"d6={g.d6*1e3:.0f} mm  ->  max reach from shoulder {1e3*(g.a2+g.d4+g.d6):.0f} mm")
    out.append(f"- Backlash requirement: J2 and J3 must have a known backlash of at most {LOW_BACKLASH[2]} arcmin")
    out.append(f"- Total moving mass in the model: {dyn.total_mass(comps):.2f} kg "
               f"(payload {[c.mass for c in comps if c.name=='payload'][0]} kg)\n")

    # ---- statics / dynamics -------------------------------------------
    st, sd, st_q = dyn.worst_case(n=30_000, alpha=ALPHA, comps=comps)
    out.append("## Worst-case joint torque\n")
    out.append(f"Random search of 30 000 poses inside the joint limits plus the stretched-out pose "
               f"and a local refinement. Dynamic = static + M(q)*alpha with alpha = {ALPHA} rad/s^2 "
               f"on every joint, safety factor {SF}. Actuator masses were fed back into the model "
               f"until the selection stopped changing.\n")
    out.append("| Joint | static (Nm) | static+dyn (Nm) | rated needed (Nm) | peak needed (Nm) | lightest candidate |")
    out.append("|---|---|---|---|---|---|")
    for j in range(6):
        need_rated, need_peak = st[j] * SF, sd[j] * SF
        cand = choice[j + 1] if j in (1, 2, 3, 4) else "not sized (needs link inertia)"
        out.append(f"| {JOINTS[j]} | {st[j]:.2f} | {sd[j]:.2f} | {need_rated:.2f} | {need_peak:.2f} | {cand} |")
    out.append("")
    out.append("J1 and J6 are listed from the point-mass model only: link rotational inertia "
               "is ignored, so their numbers are a lower bound. J1 also sees the whole arm's inertia "
               "about the vertical axis, so treat these two rows as a minimum, not a size.\n")
    out.append("Rule used: the *rated* (continuous) torque must cover the static holding "
               "torque x SF, and the *peak* torque must cover static+dynamic x SF.\n")

    # ---- backlash error budget -----------------------------------------
    bl = eb.backlash_arcmin(choice)
    sm = eb.summary(bl)
    out.append("## Tip error from gear backlash\n")
    out.append("Full backlash range of each joint turned into TCP displacement (mm) with the "
               "position Jacobian, over 3000 random poses plus the stretched-out pose. "
               f"Joints without a datasheet figure use an assumed {ASSUMED_BACKLASH_ARCMIN} arcmin "
               "(marked *). J1 uses the same part as J2.\n")
    out.append("| Joint | actuator | backlash (arcmin) | stretched pose (mm) | worst pose (mm) | median (mm) |")
    out.append("|---|---|---|---|---|---|")
    for j in range(6):
        name = choice.get(j + 1) or ("(same as J2)" if j == 0 else "n/a")
        known = ACTUATORS.get(choice.get(j + 1) or choice.get(2), {}).get("backlash") is not None
        out.append(f"| {JOINTS[j]} | {name} | {bl[j]:.0f}{'' if known else '*'} | "
                   f"{sm['stretched'][j]:.2f} | {sm['per_joint_max'][j]:.2f} | {sm['per_joint_median'][j]:.2f} |")
    out.append("")
    out.append(f"All joints combined: worst case (all at the limit, same direction) {sm['worst_sum']:.1f} mm, "
               f"root-sum-square worst {sm['worst_rss']:.1f} mm, median {sm['median_rss']:.1f} mm "
               "(full range, so roughly half of that as +/- around the commanded position).\n")
    out.append("Backlash alone does not meet a 0.5 mm goal, which is why the plan relies on "
               "camera feedback for the last step. Link deflection is not in this table yet.\n")

    # ---- payload sweep -------------------------------------------------
    out.append("## Payload sweep (shoulder J2 and elbow J3, static, x SF)\n")
    out.append("| payload (kg) | J2 (Nm) | J3 (Nm) |")
    out.append("|---|---|---|")
    pays = [0.1, 0.25, 0.5, 0.75, 1.0, 1.5]
    j2s = []
    for pay in pays:
        c = build_components(g, payload=pay, act_mass=act_mass)
        s, _, _ = dyn.worst_case(n=3000, alpha=ALPHA, comps=c, seed=3)
        j2s.append(s[1] * SF)
        out.append(f"| {pay} | {s[1]*SF:.2f} | {s[2]*SF:.2f} |")
    out.append("")
    plt.figure(figsize=(5, 3.2))
    plt.plot(pays, j2s, "o-")
    for name, v in (("AK60-6 rated", 3.0), ("AK70-10 rated", 8.3)):
        plt.axhline(v, ls="--", lw=0.8, color="gray")
        plt.text(pays[0], v + 0.2, name, fontsize=7)
    plt.xlabel("payload (kg)"); plt.ylabel("J2 torque x SF (Nm)")
    plt.title("Shoulder torque vs payload"); plt.tight_layout()
    plt.savefig(os.path.join(IMG, "payload_sweep.png"), dpi=150); plt.close()

    # ---- workspace -----------------------------------------------------
    qs, pts, man = workspace()
    r = np.hypot(pts[:, 0], pts[:, 1])
    out.append("## Workspace and singularities\n")
    out.append(f"- TCP height range: {pts[:,2].min()*1e3:.0f} .. {pts[:,2].max()*1e3:.0f} mm")
    out.append(f"- Max horizontal reach (sampled): {r.max()*1e3:.0f} mm")
    out.append(f"- Max distance from base axis incl. all poses: {np.linalg.norm(pts,axis=1).max()*1e3:.0f} mm")
    # singularity proximity, in the joint space used here (uniform sampling)
    lim = np.sin(np.radians(10))
    wrist = np.abs(np.sin(qs[:, 4])) < lim                       # J5 near 0 / 180
    elbow = np.abs(np.cos(qs[:, 2])) < lim                       # arm fully stretched or folded
    wc_r = np.array([np.hypot(*(kin.fk(q)[:2, 3] - g.d6 * kin.fk(q)[:2, 2])) for q in qs[:5000]])
    shoulder = wc_r < 0.03                                       # wrist centre near the J1 axis
    out.append("Fraction of sampled poses within 10 degrees of a singularity "
               "(uniform in joint space, so the numbers say how much of the joint range is affected, "
               "not how much of a task space):\n")
    out.append(f"- wrist (J5 near 0): {100*wrist.mean():.1f} %")
    out.append(f"- elbow (stretched / folded): {100*elbow.mean():.1f} %")
    out.append(f"- shoulder (wrist centre within 30 mm of J1 axis): {100*shoulder.mean():.1f} %\n")

    fig, ax = plt.subplots(1, 2, figsize=(9, 4))
    sc = ax[0].scatter(r, pts[:, 2], c=man, s=1, cmap="viridis")
    ax[0].set_xlabel("radius r (m)"); ax[0].set_ylabel("z (m)")
    ax[0].set_title("Reachable TCP positions (colour = manipulability)")
    ax[0].set_aspect("equal"); fig.colorbar(sc, ax=ax[0], shrink=0.8)
    ax[1].scatter(pts[:, 0], pts[:, 1], s=1, c="k", alpha=0.2)
    ax[1].set_xlabel("x (m)"); ax[1].set_ylabel("y (m)"); ax[1].set_title("Top view")
    ax[1].set_aspect("equal")
    plt.tight_layout(); plt.savefig(os.path.join(IMG, "workspace.png"), dpi=150); plt.close()

    # ---- worst pose picture -------------------------------------------
    def draw(q, fname, title):
        T = kin.frames(q, g)
        P = np.array([t[:3, 3] for t in T])
        fig, a = plt.subplots(figsize=(4.5, 4.5))
        a.plot(np.hypot(P[:, 0], P[:, 1]) * np.sign(P[:, 0] + 1e-12), P[:, 2], "o-")
        a.set_aspect("equal"); a.set_xlabel("x (m)"); a.set_ylabel("z (m)"); a.set_title(title)
        a.grid(alpha=.3); plt.tight_layout(); plt.savefig(os.path.join(IMG, fname), dpi=150); plt.close()
    draw(st_q[1], "worst_pose_j2.png", "Worst-case pose for J2")

    # ---- IK check ------------------------------------------------------
    rng = np.random.default_rng(5)
    errs, nlim = [], []
    for _ in range(2000):
        q = rng.uniform(Q_MIN, Q_MAX)
        T = kin.fk(q)
        S = kin.ik(T)
        errs.append(max(np.abs(kin.fk(s) - T).max() for s in S))
        nlim.append(sum(kin.within_limits(s, Q_MIN, Q_MAX) for s in S))
    out.append("## Inverse kinematics check\n")
    out.append(f"- 2000 random poses: max FK(IK(T)) - T error = {max(errs):.1e}")
    out.append(f"- Solutions inside joint limits per pose: min {min(nlim)}, mean {np.mean(nlim):.2f}, max {max(nlim)}\n")

    out.append("![workspace](img/workspace.png)\n![payload](img/payload_sweep.png)\n![pose](img/worst_pose_j2.png)\n")
    with open(os.path.join(ROOT, "docs", "results.md"), "w") as f:
        f.write("\n".join(out))
    print("\n".join(out))


if __name__ == "__main__":
    main()
